#!/usr/bin/env python3
"""Regenerates src/book_data.h from the Lichess chess-openings dataset (CC0).

Needs `pip install chess` (only for this generator; the build never needs it).
Usage: python3 scripts/gen_book.py

Each named opening line is replayed; every (position, next move) pair becomes a
book entry weighted by how many lines pass through it (lines whose name
contains "Gambit" count 3x, to suit the engine's taste for sacrifices).
Entries lighter than MIN_WEIGHT / MIN_SHARE are dropped.
The position key is FNV-1a over the first 3 FEN fields (placement, side,
castling) and must match position_key() in src/book.c.
"""
import collections, io, re, urllib.request
import chess

URL = "https://raw.githubusercontent.com/lichess-org/chess-openings/master/%s.tsv"
GAMBIT_WEIGHT = 3
MIN_WEIGHT = 3      # drop rarely-named side lines (e.g. 1.e4 c5 2.a4)...
MIN_SHARE = 0.05    # ...and moves under this share of their position's total weight

def fnv1a(s):
    h = 0xcbf29ce484222325
    for b in s.encode():
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h

def key(board):
    return " ".join(board.fen().split()[:3])

weights = collections.defaultdict(lambda: collections.defaultdict(int))
lines = 0
for vol in "abcde":
    text = urllib.request.urlopen(URL % vol).read().decode()
    for row in text.splitlines()[1:]:
        eco, name, pgn = row.split("\t")
        w = GAMBIT_WEIGHT if "Gambit" in name else 1
        board = chess.Board()
        for san in re.sub(r"\d+\.", " ", pgn).split():
            move = board.parse_san(san)  # raises if the line is illegal
            weights[fnv1a(key(board))][move.uci()] += w
            board.push(move)
        lines += 1

entries = [(h, m, w) for h, ms in sorted(weights.items()) for m, w in sorted(ms.items())
           if w >= MIN_WEIGHT and w >= MIN_SHARE * sum(ms.values())]
with open("src/book_data.h", "w") as f:
    f.write("// GENERATED by scripts/gen_book.py from the Lichess chess-openings dataset\n")
    f.write("// (CC0, https://github.com/lichess-org/chess-openings). Do not edit by hand.\n")
    f.write("// {position hash, UCI move, weight}\n")
    for h, m, w in entries:
        f.write('{0x%016xULL,"%s",%d},\n' % (h, m, w))
print("%d lines -> %d entries" % (lines, len(entries)))
